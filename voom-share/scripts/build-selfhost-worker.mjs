#!/usr/bin/env node
// Build the self-host worker bundle that ships inside the macOS app.
//
// The canonical hosted worker (src/index.js) serves the share/embed pages from
// the Astro build (web/dist) via the Cloudflare `ASSETS` binding. The self-host
// deploy (CloudflareDeployService) uploads a single self-contained worker.js
// with no assets binding, so this script regenerates that worker by:
//   1. Embedding every web/dist file (base64) into the worker source.
//   2. Replacing the three `env.ASSETS.fetch(...)` call sites with a lookup
//      against the embedded assets.
// It also syncs schema.sql and every numbered migration into the WorkerBundle
// so the self-host D1 schema matches the hosted one.
//
// Re-run after any change to src/index.js, web/dist, schema.sql, or migrations/:
//   cd voom-share && node scripts/build-selfhost-worker.mjs
//   (run `npm run build` inside web/ first if the Astro source changed)

import { readFileSync, writeFileSync, readdirSync, statSync, copyFileSync } from 'node:fs';
import { join, relative, dirname, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoShareDir = resolve(__dirname, '..');            // voom-share/
const distDir = join(repoShareDir, 'web', 'dist');
const indexPath = join(repoShareDir, 'src', 'index.js');
const bundleDir = resolve(repoShareDir, '..', 'Voom', 'Voom', 'Resources', 'WorkerBundle');

const CONTENT_TYPES = {
  html: 'text/html; charset=utf-8',
  css: 'text/css; charset=utf-8',
  js: 'text/javascript; charset=utf-8',
  mjs: 'text/javascript; charset=utf-8',
  json: 'application/json; charset=utf-8',
  svg: 'image/svg+xml; charset=utf-8',
  txt: 'text/plain; charset=utf-8',
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  gif: 'image/gif',
  webp: 'image/webp',
  ico: 'image/x-icon',
  woff: 'font/woff',
  woff2: 'font/woff2',
};

function contentTypeFor(path) {
  const ext = path.split('.').pop().toLowerCase();
  return CONTENT_TYPES[ext] || 'application/octet-stream';
}

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

// 1. Build the embedded asset map keyed by leading-slash, posix-style path.
const files = walk(distDir).sort();
if (files.length === 0) {
  console.error(`No files found in ${distDir}. Run \`npm run build\` in web/ first.`);
  process.exit(1);
}

const assets = {};
for (const file of files) {
  const key = '/' + relative(distDir, file).split(sep).join('/');
  const buf = readFileSync(file);
  assets[key] = { ct: contentTypeFor(key), b64: buf.toString('base64') };
}

const assetKeys = Object.keys(assets);
const expected = ['/share.html', '/embed.html', '/icon-64.png'];
for (const k of expected) {
  if (!assetKeys.includes(k)) {
    console.error(`Expected built asset ${k} is missing from web/dist.`);
    process.exit(1);
  }
}

// 2. Transform the canonical worker source.
let source = readFileSync(indexPath, 'utf8');

const replacements = [
  [
    `env.ASSETS.fetch(new Request(new URL('/share', url), request))`,
    `serveEmbeddedAsset('/share.html')`,
  ],
  [
    `env.ASSETS.fetch(new Request(new URL('/embed', url), request))`,
    `serveEmbeddedAsset('/embed.html')`,
  ],
  [
    `return env.ASSETS.fetch(request);`,
    `return serveEmbeddedAsset(path);`,
  ],
];

for (const [from, to] of replacements) {
  const count = source.split(from).length - 1;
  if (count !== 1) {
    console.error(`Expected exactly 1 occurrence of:\n  ${from}\nbut found ${count}. ` +
      `src/index.js changed — update build-selfhost-worker.mjs.`);
    process.exit(1);
  }
  source = source.replace(from, to);
}

if (source.includes('env.ASSETS')) {
  console.error('env.ASSETS still referenced after transform — aborting.');
  process.exit(1);
}

const banner = `// AUTO-GENERATED by voom-share/scripts/build-selfhost-worker.mjs — DO NOT EDIT.
// Self-contained self-host worker: canonical src/index.js with web/dist assets
// embedded so it serves the share/embed pages without a Cloudflare ASSETS binding.

const EMBEDDED_ASSETS = ${JSON.stringify(assets)};

function b64ToBytes(b64) {
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}

function serveEmbeddedAsset(path) {
  const asset = EMBEDDED_ASSETS[path];
  if (!asset) return new Response('Not found', { status: 404 });
  return new Response(b64ToBytes(asset.b64), {
    headers: { 'Content-Type': asset.ct, 'Cache-Control': 'public, max-age=3600' },
  });
}

`;

writeFileSync(join(bundleDir, 'worker.js'), banner + source);

// 3. Sync schema + migrations into the bundle.
copyFileSync(join(repoShareDir, 'schema.sql'), join(bundleDir, 'schema.sql'));

const migrationsDir = join(repoShareDir, 'migrations');
const migrationFiles = readdirSync(migrationsDir).filter(f => /^\d{4}_.*\.sql$/.test(f)).sort();
const synced = [];
for (const f of migrationFiles) {
  const num = f.slice(0, 4);
  const dest = `migration_${num}.sql`;
  copyFileSync(join(migrationsDir, f), join(bundleDir, dest));
  synced.push(dest);
}

console.log(`Wrote worker.js (${assetKeys.length} embedded assets: ${assetKeys.join(', ')})`);
console.log(`Synced schema.sql and migrations: ${synced.join(', ')}`);
